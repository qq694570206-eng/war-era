#!/usr/bin/env python3
"""Behavior tests and a reproducible synthetic demo; never calls an MCP service."""
import copy
import json
from pathlib import Path
import subprocess
import sys
import tempfile
import unittest

from PIL import Image, ImageDraw
import ui_sprites as ui


def fixture(root):
    root = Path(root)
    source = root / "source.png"
    im = Image.new("RGBA", (512, 256))
    draw = ImageDraw.Draw(im)
    for x, color in ((0, "#32667E"), (256, "#244554")):
        draw.rounded_rectangle((x + 20, 20, x + 235, 107), radius=22, fill=(0, 0, 0, 70))
        draw.rounded_rectangle((x + 24, 24, x + 231, 103), radius=18, fill="#E9BB68")
        draw.rounded_rectangle((x + 32, 32, x + 223, 95), radius=12, fill=color)
    draw.polygon([(64, 148), (104, 192), (64, 236), (24, 192)], fill="#68D7D7")
    im.save(source)
    regions = []
    for name, box, group in (("button_normal", [0, 0, 256, 128], "primary"),
                             ("button_pressed", [256, 0, 256, 128], "primary"),
                             ("icon_gem", [0, 128, 128, 128], None)):
        regions.append({"name": name, "rect": box, "background": {"mode": "alpha"},
                        "trim": not bool(group), "padding": 4,
                        "allow_edge_contact": False, "state_group": group})
    spec = {"schema_version": 1, "origin": "top-left", "source_size": [512, 256],
            "source_sha256": ui.digest(source), "regions": regions}
    ui.write_json(root / "regions.json", spec)
    return source, spec


def complete_layout(slices, target):
    layout = ui.read_json(slices / "layout.template.json")
    for item in layout["sprites"]:
        if item["name"].startswith("button"):
            item.update(border_ltrb=[52, 52, 52, 52], text_expected=True,
                        content_rect=[56, 48, 152, 40],
                        preview_sizes=[[264, 136], [360, 136], [220, 120]])
        else:
            item.update(border_ltrb=[0, 0, 0, 0], preview_sizes=[item["size"], [48, 48]])
    ui.write_json(target, layout)
    return layout


def demo(out):
    out = ui.fresh(out)
    out.mkdir(parents=True)
    source, _ = fixture(out)
    ui.inspect(source, out / "inspect", 64)
    ui.slice_sheet(source, out / "regions.json", out / "slices")
    complete_layout(out / "slices", out / "layout.json")
    ui.qa(out / "slices", out / "layout.json", out / "qa")
    print(json.dumps({"demo": str(out.resolve()), "source": "synthetic Pillow fixture, not generated by a model"}))


class PipelineTests(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory(prefix="game-ui-slicing-test-")
        self.addCleanup(self.tmp.cleanup)
        self.root = Path(self.tmp.name)
        self.source, self.spec = fixture(self.root)
        self.spec_path = self.root / "regions.json"
        self.out = self.root / "slices"

    def run_slice(self):
        ui.write_json(self.spec_path, self.spec)
        return ui.slice_sheet(self.source, self.spec_path, self.out)

    def test_full_pipeline_preserves_source_and_alpha(self):
        before = self.source.read_bytes()
        report = ui.inspect(self.source, self.root / "inspect", 64)
        self.assertGreater(report["partial_alpha_pixels"], 0)
        result = self.run_slice()
        self.assertEqual(len(result["sprites"]), 3)
        original, _, _ = ui.load_image(self.source)
        cut, _, _ = ui.load_image(self.out / "button_normal.png")
        self.assertEqual(cut.size, (264, 136))
        self.assertEqual(cut.crop((4, 4, 260, 132)).tobytes(), original.crop((0, 0, 256, 128)).tobytes())
        layout_path = self.root / "layout.json"
        complete_layout(self.out, layout_path)
        qa = ui.qa(self.out, layout_path, self.root / "qa")
        self.assertEqual(qa["geometry_checks"], "passed")
        self.assertEqual(qa["visual_review"], "required")
        self.assertEqual(qa["engine_review"], "not_performed")
        self.assertEqual(before, self.source.read_bytes())
        gem = result["sprites"][2]
        self.assertEqual(gem["trim_offset_xy"], [24, 20])
        self.assertEqual(gem["size"], [89, 97])

    def test_stale_source_hash_rejected_without_output(self):
        self.spec["source_sha256"] = "0" * 64
        with self.assertRaisesRegex(ValueError, "SHA256 changed"):
            self.run_slice()
        self.assertFalse(self.out.exists())

    def test_invalid_late_region_writes_nothing(self):
        self.spec["regions"][2]["rect"] = [500, 0, 50, 50]
        with self.assertRaisesRegex(ValueError, "outside image"):
            self.run_slice()
        self.assertFalse(self.out.exists())

    def test_clipped_ornament_cannot_be_repaired_by_padding(self):
        self.spec["regions"] = [self.spec["regions"][2]]
        self.spec["regions"][0]["rect"] = [40, 150, 40, 80]
        self.spec["regions"][0]["padding"] = 100
        with self.assertRaisesRegex(ValueError, "touches crop boundary"):
            self.run_slice()

    def test_same_state_requires_shared_canvas(self):
        self.spec["regions"][1]["rect"][2] = 250
        with self.assertRaisesRegex(ValueError, "canvas/padding mismatch"):
            self.run_slice()

    def test_state_trim_rejected(self):
        self.spec["regions"][0]["trim"] = True
        with self.assertRaisesRegex(ValueError, "trim=false"):
            self.run_slice()

    def test_reserved_and_duplicate_names_rejected(self):
        for bad in ("../x", "con", "Button", "contact-sheet", "button_normal"):
            with self.subTest(bad=bad):
                self.spec["regions"][2]["name"] = bad
                with self.assertRaises(ValueError):
                    self.run_slice()
                self.assertFalse(self.out.exists())

    def test_existing_output_cannot_be_overwritten(self):
        self.run_slice()
        old = (self.out / "manifest.json").read_bytes()
        with self.assertRaisesRegex(ValueError, "already exists"):
            self.run_slice()
        self.assertEqual(old, (self.out / "manifest.json").read_bytes())

    def test_unknown_parameter_is_not_silently_ignored(self):
        self.spec["regions"][0]["paddding"] = 20
        with self.assertRaisesRegex(ValueError, "unknown fields"):
            self.run_slice()

    def test_empty_crop_rejected(self):
        self.spec["regions"] = [self.spec["regions"][2]]
        self.spec["regions"][0]["rect"] = [400, 150, 50, 50]
        with self.assertRaisesRegex(ValueError, "no visible foreground"):
            self.run_slice()

    def test_key_scope_preserves_enclosed_same_color(self):
        im = Image.new("RGBA", (11, 11), "#FF00FF")
        ImageDraw.Draw(im).rectangle((2, 2, 8, 8), outline="green", width=2)
        settings = {"mode": "key", "key_hex": "#FF00FF", "tolerance": 0, "softness": 0, "scope": "edge"}
        edge = ui.remove_background(im, settings)
        self.assertEqual(edge.getpixel((0, 0))[3], 0)
        self.assertEqual(edge.getpixel((5, 5))[3], 255)
        all_pixels = ui.remove_background(im, {**settings, "scope": "all"})
        self.assertEqual(all_pixels.getpixel((5, 5))[3], 0)
        self.assertEqual(all_pixels.getpixel((2, 2)), im.getpixel((2, 2)))

    def test_key_soft_edge_retains_original_alpha_weight(self):
        im = Image.new("RGBA", (1, 1), (255, 15, 255, 128))
        output = ui.remove_background(im, {"mode": "key", "key_hex": "#FF00FF", "tolerance": 10,
                                             "softness": 10, "scope": "all"})
        self.assertEqual(output.getpixel((0, 0)), (255, 15, 255, 64))

    def test_palette_png_transparency_survives(self):
        im = Image.new("P", (4, 4), 0)
        im.putpalette([255, 0, 0, 0, 255, 0] + [0] * 762)
        im.putpixel((1, 1), 1)
        path = self.root / "palette.png"
        im.save(path, transparency=0)
        rgba, mode, _ = ui.load_image(path)
        self.assertEqual(mode, "P")
        self.assertEqual(rgba.getpixel((0, 0))[3], 0)
        self.assertEqual(rgba.getpixel((1, 1))[3], 255)

    def test_faint_shadow_not_trimmed_off(self):
        image = Image.new("RGBA", (16, 16))
        ImageDraw.Draw(image).rectangle((6, 6, 9, 9), fill="red")
        image.putpixel((2, 2), (0, 0, 0, 1))
        image.save(self.source)
        self.spec.update(source_size=[16, 16], source_sha256=ui.digest(self.source), regions=[{
            "name": "shadow", "rect": [0, 0, 16, 16], "background": {"mode": "alpha"},
            "trim": True, "padding": 0, "allow_edge_contact": False, "state_group": None}])
        result = self.run_slice()
        self.assertEqual(result["sprites"][0]["trim_offset_xy"], [2, 2])
        out, _, _ = ui.load_image(self.out / "shadow.png")
        self.assertEqual(out.getpixel((0, 0))[3], 1)

    def test_nine_slice_corners_unchanged(self):
        im = Image.new("RGBA", (10, 10), "yellow")
        draw = ImageDraw.Draw(im)
        for box, color in (((0, 0, 1, 1), "red"), ((8, 0, 9, 1), "green"),
                           ((0, 8, 1, 9), "blue"), ((8, 8, 9, 9), "white")):
            draw.rectangle(box, fill=color)
        out = ui.nine_slice(im, [2, 2, 2, 2], (25, 18))
        for src, dst in (((0, 0, 2, 2), (0, 0, 2, 2)), ((8, 0, 10, 2), (23, 0, 25, 2)),
                         ((0, 8, 2, 10), (0, 16, 2, 18)), ((8, 8, 10, 10), (23, 16, 25, 18))):
            self.assertEqual(im.crop(src).tobytes(), out.crop(dst).tobytes())

    def test_scaled_nine_slice_keeps_scaled_corners_and_maps_safe_rect(self):
        im = Image.new("RGBA", (100, 60), "yellow")
        ImageDraw.Draw(im).rectangle((0, 0, 19, 19), fill="red")
        out = ui.nine_slice(im, [20, 20, 20, 20], (40, 24), 0.25)
        self.assertEqual(out.crop((0, 0, 5, 5)).getextrema(), ((255, 255), (0, 0), (0, 0), (255, 255)))
        self.assertEqual(ui.display_content_rect([20, 20, 60, 20], im.size, [20, 20, 20, 20], (40, 24), 0.25), [5.0, 5.0, 30.0, 14.0])
        with self.assertRaisesRegex(ValueError, "preview_scale"):
            ui.nine_slice(im, [20, 20, 20, 20], (40, 24), 0)

    def test_edge_unmix_removes_matte_color_without_touching_center(self):
        im = Image.new("RGBA", (13, 13), "#FF00FF")
        draw = ImageDraw.Draw(im)
        draw.rectangle((2, 2, 10, 10), fill=(128, 0, 128, 255))
        draw.rectangle((3, 3, 9, 9), fill="black")
        im.putpixel((6, 6), (200, 100, 50, 255))
        spec = {"mode": "key", "key_hex": "#FF00FF", "tolerance": 0, "softness": 0, "scope": "edge"}
        base = ui.remove_background(im, spec)
        fixed = ui.remove_background(im, {**spec, "edge_unmix": 2})
        self.assertEqual(base.getpixel((2, 6)), (128, 0, 128, 255))
        self.assertEqual(fixed.getpixel((2, 6)), (0, 0, 0, 127))
        self.assertEqual(fixed.getpixel((6, 6)), im.getpixel((6, 6)))
        self.assertEqual(fixed.getpixel((0, 0))[3], 0)

    def test_alpha_does_not_accept_unmix(self):
        with self.assertRaises(ValueError):
            ui.remove_background(Image.new("RGBA", (10, 10)), {"mode": "alpha", "edge_unmix": 2})

    def test_unmix_reaches_partial_alpha_crack_with_no_clear_pixel_inside(self):
        im = Image.new("RGBA", (15, 15), "#FF00FF")
        draw = ImageDraw.Draw(im)
        draw.rectangle((2, 2, 12, 12), fill="red")
        draw.line((7, 2, 7, 8), fill=(230, 0, 230, 255))
        fixed = ui.remove_background(im, {"mode": "key", "key_hex": "#FF00FF", "tolerance": 20,
                                           "softness": 12, "scope": "edge", "edge_unmix": 2})
        self.assertEqual(fixed.getpixel((7, 7)), (0, 0, 0, 25))
        self.assertEqual(fixed.getpixel((4, 7)), im.getpixel((4, 7)))

    def test_unmix_does_not_recolor_gold_at_a_hard_edge(self):
        im = Image.new("RGBA", (9, 9), "#FF00FF")
        ImageDraw.Draw(im).rectangle((2, 2, 6, 6), fill=(200, 100, 50, 255))
        fixed = ui.remove_background(im, {"mode": "key", "key_hex": "#FF00FF", "tolerance": 0,
                                           "softness": 0, "scope": "edge", "edge_unmix": 2})
        self.assertEqual(fixed.getpixel((2, 4)), (200, 100, 50, 255))
        self.assertEqual(fixed.getpixel((0, 0))[3], 0)

    def test_canvas_downscale_halves_borders_and_safe_rect(self):
        self.run_slice()
        path = self.root / "layout.json"
        layout = complete_layout(self.out, path)
        for item in layout['sprites']:
            item['preview_sizes'] = [[264, 136], [132, 68]]
            item['preview_scales'] = [1.0, 0.5]
        ui.write_json(path, layout)
        report = ui.qa(self.out, path, self.root / "qa")
        mapped = report['sprites'][0]['displayed_content_rects']
        self.assertEqual(mapped[1]['content_rect'], [v / 2 for v in mapped[0]['content_rect']])
        layout['sprites'][0]['preview_scales'] = [1.0]
        ui.write_json(path, layout)
        with self.assertRaisesRegex(ValueError, 'preview_scales'):
            ui.qa(self.out, path, self.root / 'qa-bad')

    def test_unmix_gray_edge_does_not_turn_green(self):
        im = Image.new('RGBA', (9, 9), '#FF00FF')
        draw = ImageDraw.Draw(im)
        draw.rectangle((3, 2, 6, 6), fill=(100, 100, 100, 255))
        draw.line((2, 2, 2, 6), fill=(178, 50, 178, 255))  # 50% gray foreground on magenta.
        im.putpixel((3, 4), (129, 128, 129, 255))
        fixed = ui.remove_background(im, {'mode':'key', 'key_hex':'#FF00FF', 'tolerance':0,
                                          'softness':0, 'scope':'edge', 'edge_unmix':2})
        p = fixed.getpixel((2, 3))
        self.assertLessEqual(max(p[:3]) - min(p[:3]), 3)
        self.assertTrue(120 <= p[3] <= 135)
        self.assertEqual(fixed.getpixel((3, 4)), (129, 128, 129, 255))

    def test_missing_text_bounds_and_small_target_rejected(self):
        self.run_slice()
        path = self.root / "layout.json"
        original = complete_layout(self.out, path)
        for kind in ("missing_content", "small_target", "missing_sprite", "state_pivot"):
            layout = copy.deepcopy(original)
            if kind == "missing_content":
                layout["sprites"][0]["content_rect"] = None
            elif kind == "small_target":
                layout["sprites"][0]["preview_sizes"] = [[70, 70]]
            elif kind == "missing_sprite":
                layout["sprites"].pop()
            else:
                layout["sprites"][1]["pivot_xy"] = [0.3, 0.5]
            ui.write_json(path, layout)
            out = self.root / ("qa_" + kind)
            with self.subTest(kind=kind), self.assertRaises(ValueError):
                ui.qa(self.out, path, out)
            self.assertFalse(out.exists())

    def test_modified_sprite_invalidates_layout(self):
        self.run_slice()
        path = self.root / "layout.json"
        complete_layout(self.out, path)
        Image.new("RGBA", (264, 136), "red").save(self.out / "button_normal.png")
        with self.assertRaisesRegex(ValueError, "sprite changed"):
            ui.qa(self.out, path, self.root / "qa")

    def test_upload_copy_changes_when_same_source_path_changes(self):
        first = ui.stage_upload(self.source, self.root / "upload")
        repeat = ui.stage_upload(self.source, self.root / "upload")
        self.assertEqual(first["file_path"], repeat["file_path"])
        first_bytes = Path(first["file_path"]).read_bytes()
        Image.new("RGBA", (32, 32), "blue").save(self.source)
        second = ui.stage_upload(self.source, self.root / "upload")
        self.assertNotEqual(first["file_path"], second["file_path"])
        self.assertEqual(first_bytes, Path(first["file_path"]).read_bytes())

    def test_cli_success_and_error_exit_codes(self):
        script = str(Path(ui.__file__))
        cmd = [sys.executable, script, "inspect", str(self.source), "--out", str(self.root / "cli")]
        result = subprocess.run(cmd, capture_output=True, text=True)
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertEqual(json.loads(result.stdout)["command"], "inspect")
        result = subprocess.run(cmd, capture_output=True, text=True)
        self.assertEqual(result.returncode, 2)
        self.assertIn("already exists", result.stderr)


